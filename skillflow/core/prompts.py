def build_speed_constraint(speed: str) -> str:
    """根据 speed 枚举值生成演化约束文本。

    Args:
        speed: "low" | "medium" | "high"
    """
    return _SPEED_CONSTRAINTS.get(speed, _SPEED_CONSTRAINTS["low"])


